hexo.extend.helper.register('wulitou_resume', function () {
  if (!cache) cache = resolveResume();
  return cache;
});

// `hexo server` watches data files; drop the cache so edits show up on reload.
hexo.extend.filter.register('before_generate', () => {
  cache = null;
});

// Normalizes the currently rendering project page. Called from the detail
// layout with `page`; falls back to the matching record from `projectPages` so
// prev/next and the resume-side description stay consistent.
hexo.extend.helper.register('wulitou_project_detail', function (page) {
  const resume = this.wulitou_resume();
  const options = resume.options;
  const source = str(page && page.source).replace(/\\/g, '/');
  const dir = str(options.project_dir).replace(/^\/+|\/+$/g, '');
  const slug = source.startsWith(dir + '/')
    ? source.slice(dir.length + 1).replace(/\.[^.]+$/, '').replace(/\/index$/i, '')
    : '';

  const list = resume.projectPages;
  const index = list.findIndex(item => item.slug === slug);
  const record = index === -1 ? null : list[index];

  const name = str(page && page.title) || (record ? record.name : '') || slug;
  const cover = record ? record.rawCover : str(page && page.cover);
  const demo = record ? record.demo : normalizeUrl(page && page.demo);
  const github = record ? record.github : normalizeUrl(page && page.github);

  return {
    name,
    slug,
    description: record ? record.description : str(page && page.description),
    summary: record ? record.summary : toLines(page && page.summary),
    cover: cover || str(options.project_placeholder),
    hasCover: Boolean(cover),
    coverAlt: record ? record.coverAlt : name + ' 项目封面',
    tags: record ? record.tags : toLines(page && page.tags),
    role: record ? record.role : str(page && page.role),
    period: record ? record.period : '',
    stack: record ? record.stack : toLines(page && page.stack),
    highlights: record ? record.highlights : toLines(page && page.highlights),
    demo,
    github,
    backLabel: str(options.project_back_label) || DEFAULT_OPTIONS.project_back_label,
    // Detail pages live outside the single-page scroll, so "back" is a real
    // navigation. It leads to the list page when one is generated, otherwise
    // to the home page's projects anchor.
    backHref: resume.projects.listHref || '/#' + (str(options.project_nav_anchor) || 'projects'),
    homeLabel: str(options.back_home_label) || DEFAULT_OPTIONS.back_home_label,
    homeHref: '/',
    prev: index > 0 ? list[index - 1] : null,
    next: index !== -1 && index < list.length - 1 ? list[index + 1] : null
  };
});

// True while a page under `source/<project_dir>/` is rendering. Layout and
// sidebar use it to switch nav anchors from in-page to home-relative.
hexo.extend.helper.register('wulitou_is_project_page', function (page) {
  const options = this.wulitou_resume().options;
  const dir = str(options.project_dir).replace(/^\/+|\/+$/g, '');
  if (!dir) return false;
  return str(page && page.source).replace(/\\/g, '/').startsWith(dir + '/');
});

// True on any page that is not the single-page resume itself — detail pages and
// the generated projects list. Those pages need home-relative nav anchors and a
// pinned "项目作品" entry.
hexo.extend.helper.register('wulitou_is_subpage', function (page) {
  if (page && page.wr_projects_page) return true;
  return this.wulitou_is_project_page(page);
});

// Section anchors only resolve on the home page. From a detail page the same
// nav must navigate home first, so links become "<root>/#anchor".
hexo.extend.helper.register('wulitou_nav_href', function (anchor, isDetail) {
  const id = str(anchor);
  if (!isDetail) return '#' + id;
  const root = (str(hexo.config.root) || '/').replace(/\/+$/, '');
  return (root + '/') + '#' + id;
});

hexo.extend.helper.register('wulitou_asset', function (file) {
  const options = (hexo.theme.config || {}).theme_options || {};
  const base = str(options.decoration_path) || DEFAULT_OPTIONS.decoration_path;
  const root = str(hexo.config.root) || '/';
  const joined = (base.replace(/\/+$/, '') + '/' + str(file).replace(/^\/+/, ''));
  return (root.replace(/\/+$/, '') + '/' + joined.replace(/^\/+/, '')).replace(/\/{2,}/g, '/');
});

// Prefixes a site-absolute path with hexo's `root` so subdirectory deploys work.
hexo.extend.helper.register('wulitou_url', function (input) {
  const value = str(input);
  if (!value) return '';
  if (/^(https?:)?\/\//i.test(value) || /^(mailto|tel|data):/i.test(value)) return value;
  const root = (str(hexo.config.root) || '/').replace(/\/+$/, '');
  return (root + '/' + value.replace(/^\/+/, '')).replace(/\/{2,}/g, '/');
});

hexo.extend.helper.register('wulitou_abs_url', function (input) {
  const value = str(input);
  if (!value) return '';
  if (/^(https?:)?\/\//i.test(value) || /^data:/i.test(value)) return value;
  const site = str(hexo.config.url).replace(/\/+$/, '');
  const root = (str(hexo.config.root) || '/').replace(/\/+$/, '');
  const rel = (root + '/' + value.replace(/^\/+/, '')).replace(/\/{2,}/g, '/');
  return site ? site + rel : rel;
});

hexo.extend.helper.register('wulitou_person_jsonld', function () {
  const resume = this.wulitou_resume();
  const site = str(hexo.config.url).replace(/\/+$/, '');
  const abs = this.wulitou_abs_url.bind(this);

  const sameAs = resume.contacts
    .filter(item => item.external && item.href)
    .map(item => item.href);

  const person = {
    '@context': 'https://schema.org',
    '@type': 'Person',
    name: resume.name || str(hexo.config.title),
    jobTitle: resume.title,
    description: resume.seo.description,
    url: site || undefined,
    image: resume.avatar ? abs(resume.avatar) : undefined,
    knowsAbout: resume.skills.length ? resume.skills.map(s => s.name) : undefined,
    sameAs: sameAs.length ? sameAs : undefined
  };

  const email = resume.contacts.find(item => item.type === 'email');
  if (email) person.email = email.href.replace(/^mailto:/, '');

  const phone = resume.contacts.find(item => item.type === 'phone');
  if (phone) person.telephone = phone.text;

  const employer = resume.experience[0];
  if (employer && employer.company) {
    person.worksFor = { '@type': 'Organization', name: employer.company };
  }

  Object.keys(person).forEach(key => {
    if (isBlank(person[key])) delete person[key];
  });

  // Keeps the payload from breaking out of the <script> element.
  return JSON.stringify(person).replace(/</g, '\\u003c');
});

// Inserts <wbr> break opportunities into long machine-readable strings (emails,
// URLs) so they wrap at "@", "." and "/" instead of fracturing mid-token.
hexo.extend.helper.register('wulitou_breakable', function (input) {
  return escapeHtml(input).replace(/([@._\/-])/g, '$1<wbr>');
});

// Canonical URLs should point at the directory, not the index file.
hexo.extend.helper.register('wulitou_canonical', function (input) {
  return str(input).replace(/index\.html$/i, '');
});

hexo.extend.helper.register('wulitou_year', function () {
  return String(new Date().getFullYear());
});

