'use strict';

// Resolves resume data from (highest priority first):
//   1. site data file   _data/resume.yml   (source_dir/_data/resume.yml)
//   2. theme _config.yml  ->  resume:
//   3. built-in defaults below
//
// Templates receive one fully normalized object so they only do structure and
// simple conditionals. Every field tolerates undefined / null / '' / [].

const DEFAULTS = {
  name: '',
  avatar: '',
  title: '',
  slogan: '',
  hero: {},
  contact: {},
  about: {},
  skills: [],
  skills_note: '',
  experience: [],
  projects: {},
  resume_file: {},
  education: [],
  seo: {},
  footer: {}
};

const DEFAULT_NAV = [
  { label: '首页', anchor: 'home', icon: 'home' },
  { label: '个人简介', anchor: 'about', icon: 'user' },
  { label: '专业技能', anchor: 'skills', icon: 'code' },
  { label: '工作经历', anchor: 'experience', icon: 'briefcase' },
  { label: '项目作品', anchor: 'projects', icon: 'folder' }
];

const DEFAULT_OPTIONS = {
  nav_icons: true,
  decorations: true,
  animate_skills: true,
  smooth_scroll: true,
  decoration_path: '/images/decorations',
  project_placeholder: '/images/placeholder-project.svg',
  // Pages living under `source/<project_dir>/` render as project detail pages.
  project_dir: 'project',
  project_back_label: '返回项目作品',
  // Nav entry that stays pinned active while a detail page is open.
  project_nav_anchor: 'projects',
  // Standalone "all projects" list page, generated by the theme itself.
  projects_page: true,
  projects_page_path: 'projects/',
  projects_page_title: '项目作品',
  back_home_label: '返回首页'
};

const isPlainObject = value =>
  Object.prototype.toString.call(value) === '[object Object]';

// Treats null/undefined/''/whitespace as absent so a blank YAML value falls
// through to the next config layer instead of blanking it out.
const isBlank = value =>
  value === undefined ||
  value === null ||
  (typeof value === 'string' && value.trim() === '');

function deepMerge(base, override) {
  if (!isPlainObject(override)) return isPlainObject(base) ? clone(base) : base;

  const out = isPlainObject(base) ? clone(base) : {};

  Object.keys(override).forEach(key => {
    const value = override[key];
    if (isBlank(value)) return;
    if (Array.isArray(value)) {
      out[key] = value.slice();
    } else if (isPlainObject(value)) {
      out[key] = deepMerge(out[key], value);
    } else {
      out[key] = value;
    }
  });

  return out;
}

function clone(value) {
  if (Array.isArray(value)) return value.map(clone);
  if (isPlainObject(value)) {
    const out = {};
    Object.keys(value).forEach(key => {
      out[key] = clone(value[key]);
    });
    return out;
  }
  return value;
}

const str = value => (isBlank(value) ? '' : String(value).trim());

function escapeHtml(value) {
  return str(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

// Splits a string or array into clean paragraph/line arrays. Accepts both
// `description: text` and `description: [a, b]` shapes throughout the schema.
function toLines(value) {
  if (isBlank(value)) return [];
  const raw = Array.isArray(value) ? value : String(value).split(/\r?\n/);
  return raw.map(str).filter(Boolean);
}

function clampLevel(value) {
  const num = Number(value);
  if (!Number.isFinite(num)) return null;
  return Math.max(0, Math.min(100, Math.round(num)));
}

function normalizeUrl(value) {
  const raw = str(value);
  if (!raw) return '';
  if (/^(https?:)?\/\//i.test(raw) || /^(mailto|tel):/i.test(raw)) return raw;
  if (raw.startsWith('/')) return raw;
  return 'https://' + raw;
}

function prettyUrl(value) {
  return str(value)
    .replace(/^(https?:)?\/\//i, '')
    .replace(/\/+$/, '');
}

// `phone: '138-0000'` and `phone: {value: ..., visible: false}` both work.
// `qr` is only used by wechat — when set, the template renders a clickable
// <a data-fancybox> so the QR image opens in the lightbox.
function contactEntry(raw) {
  if (isBlank(raw)) return null;
  if (isPlainObject(raw)) {
    if (raw.visible === false) return null;
    const value = str(raw.value);
    if (!value) return null;
    return { value, label: str(raw.label), qr: str(raw.qr) };
  }
  return { value: str(raw), label: '', qr: '' };
}

function buildContacts(contact, labels) {
  const out = [];
  const phone = contactEntry(contact.phone);
  if (phone) {
    out.push({
      type: 'phone',
      icon: 'phone',
      label: labels.phone,
      text: phone.label || phone.value,
      href: 'tel:' + phone.value.replace(/[^\d+]/g, ''),
      external: false
    });
  }

  const email = contactEntry(contact.email);
  if (email) {
    out.push({
      type: 'email',
      icon: 'mail',
      label: labels.email,
      text: email.label || email.value,
      href: 'mailto:' + email.value,
      external: false
    });
  }

  // WeChat IDs are not linkable, so this one renders as plain text.
  // When `qr` is set the template wraps it in <a data-fancybox> instead.
  const wechat = contactEntry(contact.wechat);
  if (wechat) {
    out.push({
      type: 'wechat',
      icon: 'wechat',
      label: labels.wechat,
      text: wechat.label || wechat.value,
      href: '',
      external: false,
      qr: wechat.qr || ''
    });
  }

  const github = contactEntry(contact.github);
  if (github) {
    const href = normalizeUrl(github.value);
    out.push({
      type: 'github',
      icon: 'github',
      label: labels.github,
      text: github.label || prettyUrl(href) || github.value,
      href,
      external: true
    });
  }

  (Array.isArray(contact.extra) ? contact.extra : []).forEach(item => {
    if (!isPlainObject(item)) return;
    if (item.visible === false) return;
    const value = str(item.value);
    if (!value) return;
    const href = str(item.url) ? normalizeUrl(item.url) : '';
    out.push({
      type: 'extra',
      icon: str(item.icon) || 'link',
      label: str(item.label),
      text: value,
      href,
      external: /^https?:/i.test(href)
    });
  });

  return out;
}

function buildSkills(skills) {
  if (!Array.isArray(skills)) return [];
  return skills
    .map(item => {
      if (isBlank(item)) return null;
      if (!isPlainObject(item)) {
        const name = str(item);
        return name ? { name, level: null, icon: '' } : null;
      }
      const name = str(item.name);
      if (!name) return null;
      return {
        name,
        level: clampLevel(item.level),
        icon: str(item.icon)
      };
    })
    .filter(Boolean);
}

function buildExperience(experience) {
  if (!Array.isArray(experience)) return [];
  return experience
    .map(item => {
      if (!isPlainObject(item)) return null;
      const company = str(item.company);
      const position = str(item.position);
      const start = str(item.start);
      const end = str(item.end);
      const lines = toLines(item.description);
      if (!company && !position && !start && !lines.length) return null;

      let period = '';
      if (start && end) period = start + ' - ' + end;
      else period = start || end;

      return {
        company,
        position,
        period,
        lines,
        tags: toLines(item.tags)
      };
    })
    .filter(Boolean);
}

function buildProjects(projects, placeholder, pages, options) {
  const source = isPlainObject(projects) ? projects : {};
  // Accepts both `projects: [...]` and `projects: {items: [...]}`.
  const rawItems = Array.isArray(projects)
    ? projects
    : Array.isArray(source.items)
      ? source.items
      : [];

  // Detail pages are keyed by slug and by lowercased name so a resume entry can
  // opt into a detail page either explicitly (`slug:`) or just by matching title.
  const bySlug = {};
  const byName = {};
  (pages || []).forEach(detail => {
    bySlug[detail.slug] = detail;
    const key = detail.name.toLowerCase();
    if (!byName[key]) byName[key] = detail;
  });

  const used = {};

  const items = rawItems
    .map(item => {
      if (!isPlainObject(item)) return null;
      const name = str(item.name) || str(item.title);
      if (!name) return null;

      const slug = str(item.slug);
      const detail = bySlug[slug] || byName[name.toLowerCase()] || null;
      if (detail) used[detail.slug] = true;

      const demo = normalizeUrl(item.demo || item.url);
      const github = normalizeUrl(item.github || item.repo);
      const cover = str(item.cover) || str(item.image) || (detail ? detail.rawCover : '');
      return {
        name,
        description: str(item.description) || (detail ? detail.description : ''),
        cover: cover || placeholder,
        hasCover: Boolean(cover),
        coverAlt: str(item.cover_alt) || name + ' 项目封面',
        tags: toLines(item.tags).length ? toLines(item.tags) : detail ? detail.tags : [],
        demo,
        github,
        detailHref: detail ? detail.href : '',
        // Detail page wins over external links so the card leads inward when
        // there is more to read; it is a same-tab link, unlike demo/GitHub.
        primaryHref: detail ? detail.href : demo || github,
        primaryExternal: !detail && Boolean(demo || github)
      };
    })
    .filter(Boolean);

  // Markdown-only projects (no matching resume entry) still get a card, so a
  // user can drive the whole section from source/project/*.md alone.
  (pages || []).forEach(detail => {
    if (used[detail.slug]) return;
    items.push({
      name: detail.name,
      description: detail.description,
      cover: detail.rawCover || placeholder,
      hasCover: Boolean(detail.rawCover),
      coverAlt: detail.coverAlt,
      tags: detail.tags,
      demo: detail.demo,
      github: detail.github,
      detailHref: detail.href,
      primaryHref: detail.href,
      primaryExternal: false
    });
  });

  const opts = isPlainObject(options) ? options : {};
  // Site-absolute path of the generated list page, e.g. '/projects/'.
  const listPath = str(opts.projects_page_path).replace(/^\/+/, '');
  const listHref =
    opts.projects_page !== false && listPath ? '/' + listPath : '';

  const explicitMore = normalizeUrl(source.more_link);
  // An explicit `more_link` still wins, so a user can point elsewhere; the
  // generated list page is the default target once there is anything to list.
  const moreLink = explicitMore || (items.length ? listHref : '');

  return {
    items,
    listHref,
    listTitle: str(opts.projects_page_title) || '项目作品',
    moreLink,
    moreExternal: Boolean(explicitMore),
    moreLabel: str(source.more_label) || '更多项目'
  };
}

// Sidebar PDF download. Renders only when explicitly enabled AND a file is
// configured, so a user who flips the switch without supplying a PDF gets no
// button rather than a 404 link.
function buildResumeFile(raw) {
  const source = isPlainObject(raw) ? raw : {};
  if (source.enable !== true) return null;

  const url = str(source.url);
  if (!url) return null;

  const external = /^(https?:)?\/\//i.test(url);
  return {
    url,
    external,
    label: str(source.label) || '下载简历 PDF',
    // `download` only takes effect same-origin; on a cross-origin URL the
    // browser navigates instead, so the attribute is omitted there.
    filename: external ? '' : str(source.filename) || ''
  };
}

function buildEducation(education) {
  if (!Array.isArray(education)) return [];
  return education
    .map(item => {
      if (!isPlainObject(item)) return null;
      const school = str(item.school);
      const major = str(item.major) || str(item.degree);
      if (!school && !major) return null;
      const start = str(item.start);
      const end = str(item.end);
      return {
        school,
        major,
        period: start && end ? start + ' - ' + end : start || end,
        lines: toLines(item.description)
      };
    })
    .filter(Boolean);
}

function buildNav(navConfig, sections) {
  const list = Array.isArray(navConfig) && navConfig.length ? navConfig : DEFAULT_NAV;
  return list
    .map(item => {
      if (!isPlainObject(item)) return null;
      const anchor = str(item.anchor) || str(item.id);
      const label = str(item.label) || str(item.name);
      if (!anchor || !label) return null;
      return { anchor, label, icon: str(item.icon) };
    })
    .filter(Boolean)
    // Drop nav entries whose section will not render, so no anchor is dead.
    .filter(item => sections[item.anchor] !== false);
}

// Derives the slug Hexo will use for `source/<dir>/<slug>.md`, which is also
// what a resume entry writes in its `slug:` field.
function projectSlug(page, dir) {
  const source = str(page.source).replace(/\\/g, '/');
  const prefix = dir + '/';
  const rel = source.startsWith(prefix) ? source.slice(prefix.length) : source;
  return rel.replace(/\.[^.]+$/, '').replace(/\/index$/i, '');
}

// Reads `source/<project_dir>/*.md` into detail-page records. Front-matter
// mirrors the resume `projects.items` schema so a project can be described in
// either place without learning a second vocabulary.
function buildProjectPages(options) {
  const dir = str(options.project_dir).replace(/^\/+|\/+$/g, '');
  if (!dir) return [];

  const pages = (hexo.locals.get && hexo.locals.get('pages')) || [];
  const list = typeof pages.toArray === 'function' ? pages.toArray() : pages;
  const prefix = dir + '/';

  return list
    .filter(page => {
      const source = str(page.source).replace(/\\/g, '/');
      return source.startsWith(prefix);
    })
    .map(page => {
      const name = str(page.title) || projectSlug(page, dir);
      const demo = normalizeUrl(page.demo || page.url);
      const github = normalizeUrl(page.github || page.repo);
      const rawCover = str(page.cover) || str(page.image);
      const start = str(page.start);
      const end = str(page.end);
      return {
        slug: projectSlug(page, dir),
        name,
        // Leading '/' keeps the link correct from any depth; `wulitou_url`
        // adds hexo's `root` prefix at render time.
        href: '/' + str(page.path).replace(/^\/+/, ''),
        path: str(page.path),
        description: str(page.description),
        summary: toLines(page.summary || page.description),
        rawCover,
        coverAlt: str(page.cover_alt) || name + ' 项目封面',
        tags: toLines(page.tags),
        role: str(page.role),
        period: start && end ? start + ' - ' + end : start || end,
        stack: toLines(page.stack),
        highlights: toLines(page.highlights),
        demo,
        github,
        order: Number.isFinite(Number(page.order)) ? Number(page.order) : null,
        date: page.date
      };
    })
    .sort((a, b) => {
      // Explicit `order:` first (ascending), then newest date, then name.
      if (a.order !== null || b.order !== null) {
        if (a.order === null) return 1;
        if (b.order === null) return -1;
        if (a.order !== b.order) return a.order - b.order;
      }
      const at = a.date ? Number(a.date) : 0;
      const bt = b.date ? Number(b.date) : 0;
      if (at !== bt) return bt - at;
      return a.name.localeCompare(b.name);
    });
}

function resolveResume() {
  const themeConfig = hexo.theme.config || {};
  const siteData = (hexo.locals.get && hexo.locals.get('data')) || {};
  const dataResume = isPlainObject(siteData.resume)
    ? siteData.resume.resume && isPlainObject(siteData.resume.resume)
      ? siteData.resume.resume
      : siteData.resume
    : {};

  const options = deepMerge(DEFAULT_OPTIONS, themeConfig.theme_options);
  const merged = deepMerge(deepMerge(DEFAULTS, themeConfig.resume), dataResume);

  const hero = isPlainObject(merged.hero) ? merged.hero : {};
  const about = isPlainObject(merged.about) ? merged.about : {};
  const contact = isPlainObject(merged.contact) ? merged.contact : {};
  const seo = isPlainObject(merged.seo) ? merged.seo : {};
  const footer = isPlainObject(merged.footer) ? merged.footer : {};

  const name = str(merged.name);
  const avatar = str(merged.avatar);
  const contacts = buildContacts(contact, {
    phone: '电话',
    email: '邮箱',
    wechat: '微信',
    github: 'GitHub'
  });
  const skills = buildSkills(merged.skills);
  const experience = buildExperience(merged.experience);
  const projectPages = buildProjectPages(options);
  const projects = buildProjects(
    merged.projects,
    str(options.project_placeholder),
    projectPages,
    options
  );
  const education = buildEducation(merged.education);
  const resumeFile = buildResumeFile(merged.resume_file);
  const aboutParagraphs = toLines(about.content);

  const heroDescription = str(hero.description);
  const heroHighlightWord = str(hero.highlight_word);

  const sections = {
    home: true,
    about: aboutParagraphs.length > 0,
    skills: skills.length > 0,
    experience: experience.length > 0,
    projects: projects.items.length > 0
  };

  const metaDescription =
    str(seo.description) ||
    aboutParagraphs[0] ||
    [name, str(merged.title), heroDescription].filter(Boolean).join(' · ');

  return {
    options,
    name,
    avatar,
    title: str(merged.title),
    slogan: str(merged.slogan),
    // Sidebar shows "title / slogan" as two stacked lines.
    titleLines: [str(merged.title), str(merged.slogan)].filter(Boolean),
    hero: {
      prefix: str(hero.prefix),
      highlight: str(hero.highlight) || name,
      suffix: str(hero.suffix),
      description: heroDescription,
      highlightWord: heroHighlightWord,
      descriptionHtml: highlightText(heroDescription, heroHighlightWord),
      bubble: str(hero.bubble),
      image: str(hero.image) || avatar,
      imageAlt: str(hero.image_alt) || (name ? name + ' 的卡通形象' : '卡通形象'),
      hasImage: Boolean(str(hero.image) || avatar)
    },
    contacts,
    about: {
      title: str(about.title) || '个人简介',
      paragraphs: aboutParagraphs,
      bubbleLines: toLines(about.bubble)
    },
    skillsNote: str(merged.skills_note),
    skills,
    experience,
    projects,
    projectPages,
    education,
    resumeFile,
    seo: {
      description: metaDescription,
      keywords: str(seo.keywords),
      ogImage: str(seo.og_image) || str(hero.image) || avatar,
      twitterSite: str(seo.twitter_site)
    },
    footer: {
      copyright: str(footer.copyright),
      text: str(footer.text),
      icp: str(footer.icp)
    },
    sections,
    nav: buildNav(themeConfig.nav, sections)
  };
}

// Wraps the first occurrence of `word` in a highlight span. Escapes first so
// user YAML can never inject markup.
function highlightText(text, word) {
  const safe = escapeHtml(text);
  const safeWord = escapeHtml(word);
  if (!safe || !safeWord) return safe;
  const index = safe.indexOf(safeWord);
  if (index === -1) return safe;
  return (
    safe.slice(0, index) +
    '<span class="u-accent">' +
    safeWord +
    '</span>' +
    safe.slice(index + safeWord.length)
  );
}

